import csv, re, sys, os
# Writes Modules/PlaceData.lua: for every zone map, the IDs of the places (AreaTable children) inside it.
# Source: AreaTable, UiMap, UiMapAssignment of the client build 1.60.1.70888 (wago.tools, product "wowf"), as CSV:
#   https://wago.tools/db2/<Table>/csv?build=1.60.1.70888
# Usage: py tools/gen_places.py <folder with the three CSV files> [repository root]
src = sys.argv[1]
root = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def rows(name): return list(csv.DictReader(open(os.path.join(src, name), encoding='utf-8')))
A = {int(r['ID']): r for r in rows('AreaTable.csv')}
M = {int(r['ID']): r for r in rows('UiMap.csv')}
zones = {}
for u in rows('UiMapAssignment.csv'):
    mid, aid = int(u['UiMapID']), int(u['AreaID'])
    if mid in M and M[mid]['Type'] == '3' and aid:
        zones.setdefault(mid, set()).add(aid)
junk = re.compile(r'unused|^test', re.I)
out = []
out.append('-- The places inside each zone, by the number of the map (generated by tools/gen_places.py).')
out.append('-- Source: the area table of the client build 1.60.1.70888 (wago.tools, product "wowf"); places marked unused or')
out.append('-- test are left out. The names are asked from the game (C_Map.GetAreaInfo), in the language of the client.')
out.append('local ADDON, WFD = ...')
out.append('')
out.append('WFD.ZONE_PLACES = {')
total = 0
for mid in sorted(zones):
    ids = set()
    for aid in zones[mid]:
        cont = A[aid]['ContinentID']
        for i, r in A.items():
            if int(r['ParentAreaID']) == aid and r['ContinentID'] == cont and not junk.search(r['AreaName_lang']):
                ids.add(i)
    if not ids: continue
    total += len(ids)
    ids = sorted(ids)
    line = '    [%d] = { %s },   -- %s' % (mid, ', '.join(map(str, ids)), M[mid]['Name_lang'])
    out.append(line)
out.append('}')
p = os.path.join(root, 'WoWForeverDiary', 'Modules', 'PlaceData.lua')
open(p, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('zones', len(zones), 'places', total, '->', p)
